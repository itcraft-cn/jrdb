package cn.itcraft.jrdb.jdbc.config;

/**
 * 缓存级别枚举
 * 
 * <p>定义了jrdb支持的缓存级别，用于控制数据缓存策略。
 * 
 * <p>缓存级别说明：
 * <ul>
 *   <li>NONE - 不使用缓存，所有操作直接访问数据库</li>
 *   <li>L1 - 一级缓存，基于会话级别的本地缓存</li>
 *   <li>L2 - 二级缓存，基于应用级别的全局缓存</li>
 * </ul>
 * 
 * @author jrdb
 * @since 1.0.0
 */
public enum CacheLevel {
    
    /**
     * 无缓存
     * 
     * <p>不使用任何缓存机制，所有数据操作直接访问数据库。
     * 适用于对数据实时性要求极高或数据变化频繁的场景。
     */
    NONE,
    
    /**
     * 一级缓存
     * 
     * <p>会话级别的本地缓存，仅在当前会话中有效。
     * 缓存生命周期与会话绑定，会话结束后缓存自动失效。
     * 适用于会话内频繁访问相同数据的场景。
     */
    L1,
    
    /**
     * 二级缓存
     * 
     * <p>应用级别的全局缓存，在应用生命周期内有效。
     * 支持跨会话共享缓存数据，适合读多写少、数据更新不频繁的场景。
     * 注意：使用二级缓存时需要考虑缓存一致性问题。
     */
    L2
}